#!/usr/bin/env node
/*
 * Builds the native addon with Conan and cmake-js.
 *
 * The dependencies are not vendored anymore: `conan install` resolves them
 * (GDAL, PROJ, GEOS, ...) and generates build-conan/conan_toolchain.cmake,
 * which cmake-js passes to CMake. CMakeLists.txt copies the resulting addon
 * to lib/binding/<platform>-<arch>.
 *
 * Usage: node scripts/build.mjs [--debug]
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const log = (...args) => console.log('gdal-node:', ...args)

/**
 * Runs a command, printing its output
 *
 * @param {string} command
 * @param {string[]} args
 * @param {object} [env]
 * @returns {boolean} true when the command succeeded
 */
const run = (command, args, env) => {
  try {
    execFileSync(command, args, { cwd: root, stdio: 'inherit', env: env || process.env })
    return true
  } catch (e) {
    if (e.code === 'ENOENT') {
      log(`'${command}' was not found in PATH`)
    } else {
      log(`'${command} ${args.join(' ')}' failed with exit code ${e.status}`)
    }
    return false
  }
}

/**
 * Checks whether a command is available, returning its version
 *
 * @param {string} command
 * @returns {string|null} null when the command is not in PATH
 */
const probe = (command) => {
  try {
    return execFileSync(command, [ '--version' ], { stdio: [ 'ignore', 'pipe', 'ignore' ] })
      .toString().trim().split('\n')[0]
  } catch {
    return null
  }
}

/**
 * Prepares the environment of a Visual Studio developer prompt on Windows
 *
 * CMake never looks for cl.exe by itself: with the Ninja generator it needs
 * the environment that vcvarsall.bat sets up.  cmake-js prepares it only when
 * it has to pick the generator itself, which it does not do when it is given
 * Ninja on the command line, and the script generated by `conan install`
 * prepares it only for the recipes that Conan builds.  Without this
 * `npm run build` fails with "No CMAKE_CXX_COMPILER could be found"
 * unless it is run from a developer prompt.
 *
 * @returns {object} the variables to add to the environment, empty when MSVC
 * is not needed or cannot be found
 */
export const msvcEnvironment = () => {
  if (process.platform !== 'win32' || process.env.VCINSTALLDIR) {
    return {}
  }
  try {
    execFileSync('where', [ 'cl' ], { stdio: 'ignore' })
    return {}
  } catch {
    // the compiler is not in the PATH, the environment of Visual Studio is
    // needed
  }
  // the target architecture, as vcvarsall.bat names it
  const arch = { x64: 'amd64', ia32: 'x86', arm64: 'arm64' }[process.arch]
  if (!arch) {
    return {}
  }
  try {
    const vswhere = path.join(process.env['ProgramFiles(x86)'] || 'C:\\Program Files (x86)',
      'Microsoft Visual Studio', 'Installer', 'vswhere.exe')
    if (!existsSync(vswhere)) {
      log('vswhere.exe is missing: install Visual Studio with the C++ tools')
      return {}
    }
    // The MSBuild component is what the Visual Studio generator needs, but
    // Ninja needs nothing but the compiler
    const installation = execFileSync(vswhere, [ '-latest', '-products', '*',
      '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64',
      '-property', 'installationPath' ], { encoding: 'utf8' }).trim()
    if (!installation) {
      log('no Visual Studio installation with the C++ tools was found')
      return {}
    }
    const vcvarsall = path.join(installation, 'VC', 'Auxiliary', 'Build', 'vcvarsall.bat')
    if (!existsSync(vcvarsall)) {
      log(`vcvarsall.bat is missing in ${installation}`)
      return {}
    }
    // cmd mangles the quoting of a path given to /c together with other
    // arguments, so the script runs by its bare name, from its own directory
    // `>nul` hides the banner and the SDK paths that vcvarsall prints, the
    // code page is switched to UTF-8 so that a path with non-ASCII characters
    // (a user name in C:\Users\...) survives the round trip through cmd
    const dir = mkdtempSync(path.join(os.tmpdir(), 'gdal-node-'))
    let output
    try {
      writeFileSync(path.join(dir, 'vcvars.bat'),
        `@echo off\r\nchcp 65001 >nul\r\ncall "${vcvarsall}" ${arch} >nul\r\nset\r\n`)
      output = execFileSync(process.env.ComSpec || 'cmd.exe', [ '/d', '/s', '/c', 'vcvars.bat' ],
        { encoding: 'utf8', cwd: dir })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
    log(`using the Visual Studio environment of ${installation}`)
    // Only the variable definitions: the banner and any other line cmd prints
    // (with a '=' in a message, for instance) must not become variables
    return Object.fromEntries(output.split(/\r?\n/).filter((line) => /^[A-Za-z_][A-Za-z0-9_]*=/.test(line))
      .map((line) => [ line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1) ]))
  } catch (e) {
    log(`could not prepare the Visual Studio environment: ${e.message.split('\n')[0]}`)
    return {}
  }
}

/**
 * Builds the addon, reporting whether it was built
 *
 * @param {boolean} [debug] build a debug addon
 * @returns {boolean}
 */
export const buildFromSource = (debug = false) => {
  const toolchain = path.join(root, 'build-conan', 'conan_toolchain.cmake')
  const env = { ...process.env, ...msvcEnvironment() }
  // CMake 4 refuses the cmake_minimum_required() older than 3.5 that several
  // of the dependencies still declare when Conan has to build them.  This has
  // to be an environment variable: a variable set by the generated toolchain
  // is set too late for the projects that need it
  env.CMAKE_POLICY_VERSION_MINIMUM = '3.5'
  // Ninja wherever it is available, including Windows, where cmake-js would
  // otherwise pick the Visual Studio generator: that one cannot produce the
  // compile_commands.json that CMakeLists.txt exports for clangd, clang-tidy
  // and the editors, and it is much slower.  CMAKE_GENERATOR overrides it.
  const generator = process.env.CMAKE_GENERATOR || (probe('ninja') ? 'Ninja' : null)
  if (generator) {
    log(`using the ${generator} generator`)
  } else {
    log('ninja was not found in PATH, cmake-js will pick the generator ' +
      '(the compilation database is only exported by the Ninja and Makefile generators)')
  }
  log('resolving the dependencies with Conan')
  // conan/recipes/gdal is a fork of the recipe of conan-center: it also
  // carries the ExprTk and muparser options the addon needs.  Exporting it
  // here makes the CI and the developers use the very same recipe
  if (!run('conan', [ 'export', path.join(root, 'conan', 'recipes', 'gdal') ], env)) {
    return false
  }

  // --build=missing so that a toolchain without prebuilt dependencies
  // (a distribution that Conan has no binaries for) still works
  // C++20 because the addon needs it for the V8 headers and the profile
  // written by `conan profile detect` may default to a lower standard
  // In the CI the pinned profiles of conan/profiles are used instead: they
  // name the compilers that conan-center has published the binaries with,
  // while the compilers of a runner are usually newer - Conan would then
  // rebuild the whole dependency tree from source on every run.  They also
  // select Ninja over the MSBuild generator that Conan picks by default on
  // Windows.  Keep them in sync with the runners pinned by
  // .github/workflows/test-dev.yml
  // The architecture is part of the name for every platform that has a profile
  // of each: a profile that pins an architecture the machine does not have
  // cross-compiles the dependencies, and the executables of the build context
  // - the sqlite3 that generates proj.db, for one - are then built for a CPU
  // that cannot run them
  const arm64 = process.arch === 'arm64'
  const pinnedPlatform = {
    darwin: `macos-${arm64 ? 'arm64' : 'x64'}`,
    linux: `linux${arm64 ? '-arm64' : ''}`,
    win32: `windows${arm64 ? '-arm64' : ''}`
  }[process.platform]
  const pinned = pinnedPlatform ? path.join(root, 'conan', 'profiles', pinnedPlatform) : null
  const profiles = process.env.CI && pinned && existsSync(pinned) ? [ `-pr:h=${pinned}`, `-pr:b=${pinned}` ] : []
  if (!run('conan', [ 'install', '.', '-of', 'build-conan', '--build=missing',
    '-s', `build_type=${debug ? 'Debug' : 'Release'}`, '-s', 'compiler.cppstd=20',
    // the generator of the generated toolchain has to be the one of cmake-js:
    // Conan asks for the MSBuild platform by default on Windows and CMake then
    // refuses to configure Ninja
    ...(generator ? [ '-c', `tools.cmake.cmaketoolchain:generator=${generator}` ] : []),
    ...profiles ], env)) {
    log('install Conan from https://conan.io/downloads and try again')
    return false
  }
  if (!existsSync(toolchain)) {
    log(`Conan did not generate ${path.relative(root, toolchain)}`)
    return false
  }
  env.CMAKE_TOOLCHAIN_FILE = toolchain
  const cmakejs = path.join(root, 'node_modules', 'cmake-js', 'bin', 'cmake-js')
  if (!existsSync(cmakejs)) {
    log('cmake-js is missing, run `npm install` first')
    return false
  }
  log('building the addon with cmake-js')
  const args = [ cmakejs, 'build' ]
  if (generator) {
    args.push('--generator', generator)
  }
  if (debug) {
    args.push('--debug')
  }
  return run(process.execPath, args, env)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(buildFromSource(process.argv.includes('--debug')) ? 0 : 1)
}
